const DICT = { en, zh }

export function useLang(): Lang {
  return useSearch({
    strict: false,
    select: (s: { lang?: string }) => (s.lang === 'zh' ? 'zh' : 'en'),
  })
}

export function useT() {
  const dict = DICT[useLang()]
  return (key: MessageKey | (string & {}), vars?: Record<string, string | number>) => {
    const text = dict[key as MessageKey] ?? key
    return vars ? text.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? '')) : text
  }
}
